export const getSiteContext = (site) => {
    const entry = Object.prototype.hasOwnProperty.call(siteGroups, site) ? siteGroups[site] : null;
    return {site: entry ? site : 'general', name: entry ? entry[0] : '', group: entry ? entry[1] : 'general'};
};

export const pickMessageIndex = (count, previous, random) => {
    if (count <= 1) return 0;
    const hasPrevious = Number.isInteger(previous) && previous >= 0 && previous < count;
    const candidate = Math.min(count - (hasPrevious ? 2 : 1), Math.floor(random * (count - (hasPrevious ? 1 : 0))));
    return hasPrevious && candidate >= previous ? candidate + 1 : candidate;
};
